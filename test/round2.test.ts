import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { verifyAudit } from "../src/audit.js";
import { checkGcode } from "../src/guard.js";
import { analyzeGcode, applyFixes, findLayerStart } from "../src/preflight.js";
import { bootServer, closeAll } from "./helpers/bootServer.js";

afterEach(closeAll);
const cfg: any = { host: "x", password: "", readOnly: false, cameras: {}, macros: [], maxTemp: { bed: 100, tool: 260 } };

describe("M600 and M226 are not sent as commands", () => {
  it("are refused with the reason and the alternative", () => {
    for (const g of ["M600", "M226", "m600 ; now"]) {
      const v = checkGcode(g, cfg, undefined, true);
      expect(v.ok).toBe(false);
      expect((v as any).reason).toMatch(/inside the G-code file/);
      expect((v as any).reason).toMatch(/pause_job/);
    }
    expect(checkGcode("M25", cfg, undefined, true).ok).toBe(true);
  });
});

describe("filament change inserted into a G-code copy", () => {
  const cura = [";FLAVOR:Marlin", "M140 S55", "M104 S220", ";LAYER:0", "G1 X1 E1", ";LAYER:1", "G1 X2 E2", ";LAYER:2", "G1 X3 E3", ";LAYER:3", "G1 X4 E4", "M104 S0"];
  const prusa = ["; generated by PrusaSlicer", "M104 S210", ";LAYER_CHANGE", "G1 Z.2", ";LAYER_CHANGE", "G1 Z.4", ";LAYER_CHANGE", "G1 Z.6", "M104 S0"];

  it("finds the start of a layer, counted from 1 like the firmware", () => {
    expect(findLayerStart(cura, 3)).toMatchObject({ index: 8, marker: ";LAYER:2" }); // the line after ";LAYER:2"
    expect(findLayerStart(prusa, 2)).toMatchObject({ index: 5, marker: ";LAYER_CHANGE" });
    expect(findLayerStart(cura, 1)).toBeUndefined(); // never before the first layer
    expect(findLayerStart(cura, 9)).toBeUndefined();
  });

  it("writes M600 right after the layer marker and leaves the rest alone", () => {
    const text = cura.join("\n");
    const out = applyFixes(text, analyzeGcode(text, { maxTemp: { bed: 100, tool: 260 } }), [], 3);
    const lines = out.text.split("\n");
    expect(lines.indexOf(";LAYER:2")).toBe(7);
    expect(lines[8]).toMatch(/^M600 /);
    expect(lines.filter((l) => l.startsWith("M600"))).toHaveLength(1);
    expect(lines.length).toBe(cura.length + 1);
    expect(out.changes[0]).toMatch(/M600 inserted before layer 3/);
  });

  it("says so when the file has no layer markers", () => {
    const text = ["M104 S200", "G1 X1 E1", "M104 S0"].join("\n");
    const out = applyFixes(text, analyzeGcode(text, { maxTemp: { bed: 100, tool: 260 } }), [], 4);
    expect(out.text).toBe(text);
    expect(out.changes[0]).toMatch(/M600 NOT inserted/);
  });

  it("works through the tool and never touches the original", async () => {
    const dir = mkdtempSync(join(tmpdir(), "m600-"));
    const file = join(dir, "tower.gcode");
    writeFileSync(file, cura.join("\n"));
    const { call } = await bootServer({ readOnly: true });
    const r = await call("preflight_gcode", { file, filamentChangeAtLayer: 3 });
    expect(r.text).toMatch(/Patched copy written to .*tower\.duet\.gcode/);
    expect(r.text).toMatch(/M600 inserted before layer 3/);
    expect(readFileSync(file, "utf8")).toBe(cura.join("\n"));
    expect(readFileSync(join(dir, "tower.duet.gcode"), "utf8")).toMatch(/\nM600 /);
  }, 30000);
});

describe("uploads and the Duet being busy", () => {
  it("tries again after a transient HTTP 500", async () => {
    const dir = mkdtempSync(join(tmpdir(), "up-"));
    const f = join(dir, "a.gcode");
    writeFileSync(f, "G28\n");
    const { call, mock } = await bootServer({ readOnly: false, initial: { uploadHttpFail: 2 } });
    const r = await call("upload_file", { localPath: f, remoteName: "a.gcode" });
    expect(r.isError).toBe(false);
    expect(mock.state.uploadAttempts).toBe(3);
    expect(mock.state.uploads["0:/gcodes/a.gcode"]).toBe(4);
  }, 40000);

  it("gives up with a clear error after three busy answers", async () => {
    const dir = mkdtempSync(join(tmpdir(), "up-"));
    const f = join(dir, "a.gcode");
    writeFileSync(f, "G28\n");
    const { call, mock } = await bootServer({ readOnly: false, initial: { uploadHttpFail: 5 } });
    const r = await call("upload_file", { localPath: f, remoteName: "a.gcode" });
    expect(r.isError).toBe(true);
    expect(r.text).toMatch(/HTTP 500/);
    expect(mock.state.uploadAttempts).toBe(3);
  }, 40000);
});

describe("DUET_AUDIT_READS", () => {
  it("logs read-only calls only when asked, and the chain still verifies", async () => {
    const quiet = await bootServer({ readOnly: true });
    await quiet.call("get_machine_info");
    let none = "";
    try { none = readFileSync(quiet.auditFile, "utf8"); } catch { /* no file: nothing was logged */ }
    expect(none).not.toMatch(/get_machine_info/);

    const loud = await bootServer({ readOnly: true, env: { DUET_AUDIT_READS: "on" } });
    await loud.call("get_machine_info");
    await loud.call("list_cameras");
    const text = readFileSync(loud.auditFile, "utf8");
    expect(text).toMatch(/"tool":"get_machine_info".*"read":true/);
    expect(text).toMatch(/"tool":"list_cameras"/);
    expect(verifyAudit(text).ok).toBe(true);
  }, 40000);
});
